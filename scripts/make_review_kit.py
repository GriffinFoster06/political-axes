#!/usr/bin/env python3
"""Build the reviewer materials from the draft bank.

    python3 scripts/make_review_kit.py

Writes:
  review/packet.md          every question, readable, grouped by topic area
  review/review_sheet.csv   one row per question (and per exception case),
                            with blank columns reviewers fill in; imports
                            straight into Google Sheets or Excel
"""
from __future__ import annotations

import csv
import json
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "review"

SHEET_COLS = [
    "domain", "item_id", "case_id", "format", "question", "answers",
    # filled in by the reviewer
    "in_your_own_words_what_is_it_asking", "your_answer_letter",
    "slant_1_to_5", "slant_favors_which_side", "straw_man_option_letter",
    "missing_position", "confusing_words", "other_notes",
]
FORMAT_NOTE = {
    "tradeoff": "Two sides shown; answer Clearly or Lean toward one.",
    "exceptions": "Answer each case separately.",
    "agree_defined": "Each scale point has the meaning shown.",
}


def letters(opts):
    return [f"{string.ascii_uppercase[k]}. {o}" for k, o in enumerate(opts)]


def main():
    OUT.mkdir(exist_ok=True)
    files = sorted((ROOT / "items" / "drafts").glob("d*.json"))
    core = {it["id"]: it for it in json.loads((ROOT / "items" / "drafts" / "core_v0.json").read_text())["items"]}
    bp = {}
    import csv as _csv
    with open(ROOT / "items" / "blueprint.csv", newline="") as f:
        for r in _csv.DictReader(f):
            bp[r["subtopic"]] = (r["domain_id"], r["domain"])
    by_dom = {}
    for p in files:
        d = json.loads(p.read_text())
        by_dom.setdefault((d["domain_id"], d["domain"]), []).extend(d["items"])
    for it in core.values():
        did, dname = bp[it["subtopic"]]
        by_dom.setdefault((did, dname), []).append(it)
    for key in by_dom:  # keep blueprint subtopic order within each domain
        order = [s for s in bp if bp[s][0] == key[0]]
        by_dom[key].sort(key=lambda it: order.index(it["subtopic"]))

    md = ["# Review packet", "",
          "Every draft question, as a quiz taker would read it. Answer letters are for reference only; "
          "the app shows answers in random direction (A-to-last or last-to-A). Every question also offers "
          "\"None of these fit my view\" and \"I don't know enough about this to say\".", "",
          "Generated by `scripts/make_review_kit.py`; do not edit by hand.", ""]
    rows = []
    for (did, dname), items in sorted(by_dom.items()):
        md += [f"## {did} {dname}", ""]
        for it in items:
            md.append(f"### `{it['id']}`  ·  {it['format']}  ·  {it['subtopic']}")
            md.append("")
            if it.get("context"):
                md.append(f"*Context shown:* {it['context']}")
                md.append("")
            md.append(f"**{it['stem']}**")
            md.append("")
            md.append(f"*{it['scope']}*")
            md.append("")
            if it["format"] == "tradeoff":
                for k, s in enumerate(it["sides"]):
                    md.append(f"- **{'AB'[k]} ({s['label']}):** {s['text']}")
                md.append("- Answers: Clearly A / Lean A / Lean B / Clearly B")
            else:
                for line in letters(it["options"]):
                    md.append(f"- {line}")
            if it.get("point_meanings"):
                md.append("")
                md.append("Meanings: " + "; ".join(f"{o} = {m}" for o, m in zip(it["options"], it["point_meanings"])))
            if it.get("cases"):
                md.append("")
                md.append("Cases:")
                for c in it["cases"]:
                    md.append(f"  - `{c['id']}` {c['text']}")
            for dfn in it.get("definitions", []):
                md.append("")
                md.append(f"*Definition of \"{dfn['term']}\":* {dfn['text']}")
            if it.get("show_if"):
                parent, codes = next(iter(it["show_if"].items()))
                md.append("")
                md.append(f"*Shown only to people who chose answer(s) "
                          f"{', '.join(string.ascii_uppercase[c] for c in codes)} on `{parent}`.*")
            md.append("")
            answers = (" | ".join(f"{'AB'[k]} ({s['label']}): {s['text']}" for k, s in enumerate(it["sides"]))
                       if it["format"] == "tradeoff" else " | ".join(letters(it["options"])))
            question = " ".join(x for x in [it.get("context", ""), it["stem"], it["scope"],
                                            FORMAT_NOTE.get(it["format"], "")] if x)
            if it.get("cases"):
                for c in it["cases"]:
                    rows.append({"domain": f"{did} {dname}", "item_id": it["id"], "case_id": c["id"],
                                 "format": it["format"], "question": f"{question} CASE: {c['text']}",
                                 "answers": answers})
            else:
                rows.append({"domain": f"{did} {dname}", "item_id": it["id"], "case_id": "",
                             "format": it["format"], "question": question, "answers": answers})
    (OUT / "packet.md").write_text("\n".join(md) + "\n")
    with open(OUT / "review_sheet.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=SHEET_COLS)
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in SHEET_COLS})
    print(f"wrote review/packet.md ({sum(len(v) for v in by_dom.values())} questions) and "
          f"review/review_sheet.csv ({len(rows)} rows)")


if __name__ == "__main__":
    main()
