#!/usr/bin/env python3
"""Balance and review audit of the draft question bank.

Writes reports/item_audit.md: things a human reviewer should look at that the
validator can't decide on its own.

    python3 scripts/audit_items.py

Checks:
1. Status-quo position: where the "as today" option sits in each ladder. If
   current law is at one end, the ladder offers change in only one direction;
   that is sometimes right (e.g. no limit exists today) but must be a choice.
2. Length asymmetry: options on one half of a ladder much wordier than the
   other half can read as more carefully argued (a slant signal).
3. Near-duplicate stems across the bank.
4. Open fact checks (verify=true) and definitions to verify.
5. Reading level above target.
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from validate_items import fk_grade, words  # noqa: E402

SQ = re.compile(r"\b(as today|as now|today's|as it is|as they are|current law|as current|keep it (?:at|as)|"
                r"keep (?:about )?(?:the )?(?:same|today)|roughly today|as (?:most|federal) .* (?:do|requires?) now)\b", re.I)


def tokens(s):
    return set(re.findall(r"[a-z]+", s.lower())) - {"the", "a", "of", "to", "in", "and", "be", "should", "what",
                                                    "which", "comes", "closest", "your", "view", "for", "on", "or"}


def main():
    items = []
    for p in sorted((ROOT / "items" / "drafts").glob("*.json")):
        for it in json.loads(p.read_text())["items"]:
            it["_file"] = p.name
            items.append(it)
    out = ["# Item audit", "", f"Generated by `scripts/audit_items.py` over {len(items)} draft items.", ""]

    # 1. status quo position
    sq_rows, sq_pos = [], Counter()
    for it in items:
        opts = it.get("options", [])
        if it["format"] in ("tradeoff", "exceptions", "agree_defined") or len(opts) < 3:
            continue
        hits = [k for k, o in enumerate(opts) if SQ.search(o)]
        if not hits:
            continue
        k = hits[0]
        where = "end" if k in (0, len(opts) - 1) else "middle"
        sq_pos[where] += 1
        if where == "end":
            sq_rows.append(f"| `{it['id']}` | {k + 1} of {len(opts)} | {opts[k]} |")
    out += ["## 1. Where current law sits in each ladder", "",
            f"Ladders with a marked current-law option: {sum(sq_pos.values())}; "
            f"in the middle: {sq_pos['middle']}; at an end: {sq_pos['end']}.", "",
            "Current law at an end means every other option moves the same way. Review each: keep it only if no "
            "real position (held by ~3%+) lies beyond current law in the other direction.", "",
            "| Item | Position | Option |", "|---|---|---|"] + sq_rows + [""]

    # 2. length asymmetry
    asym = []
    for it in items:
        opts = it.get("options", [])
        if it["format"] in ("tradeoff", "exceptions", "agree_defined", "frequency") or len(opts) < 3:
            continue
        h = len(opts) // 2
        lo = sum(words(o) for o in opts[:h]) / h
        hi = sum(words(o) for o in opts[-h:]) / h
        r = max(lo, hi) / max(1, min(lo, hi))
        if r >= 1.8 and max(lo, hi) >= 8:
            side = "low-code half" if lo > hi else "high-code half"
            asym.append(f"| `{it['id']}` | {r:.1f}x | {side} ({it['high_pole']} is high) |")
    for it in items:
        if it["format"] == "tradeoff":
            a, b = (words(s["text"]) for s in it["sides"])
            r = max(a, b) / max(1, min(a, b))
            if r >= 1.5:
                asym.append(f"| `{it['id']}` (tradeoff) | {r:.1f}x | side {'A' if a > b else 'B'} longer |")
    out += ["## 2. Wording-length asymmetry", "",
            "Options on one half of the ladder averaging 1.8x+ the words of the other half (tradeoff sides: 1.5x+). "
            "Longer options can read as more reasonable. Check each with the steelman test.", "",
            "| Item | Ratio | Wordier side |", "|---|---|---|"] + (asym or ["| none | | |"]) + [""]

    # 3. near-duplicate stems
    dups = []
    for i in range(len(items)):
        ti = tokens(items[i]["stem"])
        for j in range(i + 1, len(items)):
            tj = tokens(items[j]["stem"])
            if ti and tj:
                jac = len(ti & tj) / len(ti | tj)
                if jac >= 0.5:
                    dups.append(f"| `{items[i]['id']}` | `{items[j]['id']}` | {jac:.2f} |")
    out += ["## 3. Similar stems", "", "Stem word overlap (Jaccard) of 0.5 or more. Usually intended pairs "
            "(e.g. the same question for different groups); confirm each asks something distinct.", "",
            "| Item | Item | Overlap |", "|---|---|---|"] + (dups or ["| none | | |"]) + [""]

    # 4. open fact checks
    fc = []
    for it in items:
        for f in it.get("facts", []):
            if f.get("verify"):
                fc.append(f"- [ ] `{it['id']}`: {f['claim']} ({f['source']})")
        for d in it.get("definitions", []):
            if d.get("verify"):
                fc.append(f"- [ ] `{it['id']}` definition of *{d['term']}* ({d['source']})")
    out += ["## 4. Facts and definitions still to verify against a primary source", ""] + (fc or ["None."]) + [""]

    # 5. reading level
    rl = sorted(((fk_grade(it["stem"] + " " + it["scope"]), it["id"]) for it in items), reverse=True)
    high = [f"| `{i}` | {g:.1f} |" for g, i in rl if g > 9.0]
    out += ["## 5. Reading level above grade 9 (stem + scope)", "",
            "The Flesch-Kincaid formula overcounts long common words like 'government' and 'organizations', so "
            "many of these read fine aloud. Think-aloud interviews decide; rewrite any that people misread.", "",
            f"{len(high)} of {len(items)} items.", "", "| Item | Grade |", "|---|---|"] + high + [""]

    # summary by axis and format
    ax = defaultdict(Counter)
    for it in items:
        n = len(it["cases"]) if it["format"] == "exceptions" else 1
        ax[it["axis"][0]][it["format"]] += n
    out += ["## 6. Scored units by primary axis and format", "", "| Axis | Units | Formats |", "|---|---|---|"]
    for a in sorted(ax):
        out.append(f"| {a} | {sum(ax[a].values())} | " + ", ".join(f"{k} {v}" for k, v in ax[a].most_common()) + " |")
    out.append("")
    (ROOT / "reports" / "item_audit.md").write_text("\n".join(out))
    print(f"wrote reports/item_audit.md: {sq_pos['end']} status-quo-at-end, {len(asym)} asymmetric, "
          f"{len(dups)} similar pairs, {len(fc)} open checks, {len(high)} high reading level")


if __name__ == "__main__":
    main()
